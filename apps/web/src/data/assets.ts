const map = new Map(assets.map((a) => [a.id, a]))
export function asset(id: string): Asset {
  const a = map.get(id)
  if (!a) throw new Error(`Unknown asset ${id}`)
  return a
}
export const assetByCode = (code: string) => assets.find((a) => a.code === code)
export const releasedAssets = () => assets.filter((a) => a.passport.status === 'released')

/** Owner-facing: plain workstream status counts */
export function flagCounts(assetId: string, flags: { assetId: string; severity: string; status: string }[]) {
  const open = flags.filter((f) => f.assetId === assetId && f.status !== 'resolved')
  return {
    critical: open.filter((f) => f.severity === 'critical').length,
    high: open.filter((f) => f.severity === 'high').length,
    medium: open.filter((f) => f.severity === 'medium').length,
    low: open.filter((f) => f.severity === 'low').length,
  }
}
